// Builds src/modules/lawyers/governorates.ts from the app's places file (assets/data/egypt_places.json).
// Only the cities and big towns are kept, so the server and the phone pick the same governorate for a point.
// Run again whenever the places file changes: node --import tsx scripts/build-governorates.ts
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(here, '../../assets/data/egypt_places.json');
const target = path.resolve(here, '../src/modules/lawyers/governorates.ts');

const data = JSON.parse(fs.readFileSync(source, 'utf8')) as { governorates: string[]; places: [string, number, number, number, number][] };
const names = [...new Set(data.governorates)];
const points = data.places
  .filter((place) => place[3] >= 2)
  .map((place) => [Number(place[1].toFixed(3)), Number(place[2].toFixed(3)), names.indexOf(data.governorates[place[4]])]);

fs.writeFileSync(
  target,
  `// Generated by scripts/build-governorates.ts from assets/data/egypt_places.json, do not edit by hand.
// Cities and big towns with their governorate. A point belongs to the governorate of the nearest one.
export const GOVERNORATES: string[] = ${JSON.stringify(names)};
export const GOVERNORATE_POINTS: [number, number, number][] = ${JSON.stringify(points)};
`
);
console.log(`${names.length} governorates, ${points.length} points`);
