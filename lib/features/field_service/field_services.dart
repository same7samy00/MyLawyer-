/// الخدمات الميدانية: محامي بيروح مكان باسمه (قسم، نيابة، محكمة، مصلحة) للموكل أو لشخص تاني.
/// منفصلة عن «محاميك حالاً»: شاشاتها هنا، ومسارها `/field` في الخادم (`docs/FIELD_SERVICES.md`)
class FieldServices {
  FieldServices._();

  /// أسماء الخدمات زي ما بتتبعت للسيرفر، وفي الخانة المكتوبة تحت البحث
  static const Map<String, String> placeHints = {
    'محضر في قسم الشرطة': 'اسم القسم، مثلًا: قسم المعادي',
    'تحقيق عاجل في النيابة العامة': 'اسم النيابة، مثلًا: نيابة الجيزة',
    'حضور جلسة': 'اسم المحكمة، مثلًا: محكمة جنوب القاهرة',
    'حضور مجلس عرفي': 'مكان المجلس أو اسم البلد',
    'إجراءات إدارية': 'اسم المصلحة، مثلًا: الشهر العقاري',
  };

  static bool isField(String? title) => title != null && placeHints.containsKey(title);

  /// سؤال «محبوس أو محتجز؟» بيظهر في القسم والنيابة بس
  static bool asksDetained(String title) => title == 'محضر في قسم الشرطة' || title == 'تحقيق عاجل في النيابة العامة';

  static String placeHint(String title) => placeHints[title] ?? 'اسم المكان';

  /// الصلات اللي الموكل يختار منها بضغطة
  static const List<String> relations = ['أخ أو أخت', 'أب أو أم', 'ابن أو بنت', 'زوج أو زوجة', 'قريب', 'صديق', 'زميل'];
}
